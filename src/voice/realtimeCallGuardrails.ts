/** Replaces old prompt-control sections while preserving business scenario data. */
export function withRealtimeCallGuardrails(prompt: string): string {
  const companyStart = prompt.indexOf(COMPANY_SECTION_START);
  if (companyStart < 0) return `${REALTIME_CALL_GUARDRAILS}\n\n${prompt.trimStart()}`;

  const explicitStart = prompt.indexOf(GUARDRAILS_SECTION_START);
  const legacyStart = prompt.indexOf(LEGACY_VOICEMAIL_SECTION_START);
  const replacementStart = explicitStart >= 0 && explicitStart < companyStart
    ? explicitStart
    : legacyStart >= 0 && legacyStart < companyStart
      ? legacyStart
      : companyStart;

  return [
    prompt.slice(0, replacementStart).trimEnd(),
    REALTIME_CALL_GUARDRAILS,
    prompt.slice(companyStart),
  ].filter(Boolean).join('\n\n');
}
